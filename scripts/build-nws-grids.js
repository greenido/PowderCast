#!/usr/bin/env node
/**
 * Resolve every US resort's NWS forecast grid cell, once, at build time.
 *
 * The first thing every US forecast did was ask api.weather.gov/points which
 * grid cell a coordinate falls in, then wait for the answer before it could
 * request the forecast itself. The answer only changes when NWS re-grids an
 * office, which is rare, so it is looked up here instead and shipped in
 * resorts.json. The provider still falls back to /points if a stored cell
 * 404s, so a stale entry costs one round trip rather than a broken forecast.
 *
 * Writes data/nws-grids.json (merged by build-resorts.js on regeneration) and
 * patches public/resorts.json in place, so this can run on its own.
 *
 *   yarn build:nws-grids
 */

const fs = require('fs');
const path = require('path');

const RESORTS_PATH = path.join(__dirname, '..', 'public', 'resorts.json');
const GRIDS_PATH = path.join(__dirname, '..', 'data', 'nws-grids.json');

// Same identification the app's provider sends; NWS asks API users for one.
const HEADERS = {
  'User-Agent': 'PowderCast/2.0 (contact@powdercast.app)',
  Accept: 'application/geo+json',
};

/** Polite: NWS rate-limits bursts, and nothing here is in a hurry. */
const CONCURRENCY = 3;
const ATTEMPTS = 3;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function lookUp(lat, lon) {
  // Same formatting as the app's /points request, so the cell matches exactly.
  const url = `https://api.weather.gov/points/${lat},${lon}`;
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    const res = await fetch(url, { headers: HEADERS });
    if (res.ok) {
      const { properties: p } = await res.json();
      return { office: p.gridId, x: p.gridX, y: p.gridY };
    }
    // Outside the NWS domain. Not an error: the resort just goes without.
    if (res.status === 404) return null;
    if (attempt < ATTEMPTS) await sleep(1000 * attempt);
    else throw new Error(`${url} -> HTTP ${res.status}`);
  }
  return null;
}

async function main() {
  const resorts = JSON.parse(fs.readFileSync(RESORTS_PATH, 'utf8'));
  const us = resorts.filter((r) => r.country === 'US');
  console.log(`🔍 Resolving NWS grid cells for ${us.length} US resorts...`);

  const grids = {};
  const failures = [];
  let cursor = 0;

  async function worker() {
    while (cursor < us.length) {
      const resort = us[cursor++];
      try {
        const grid = await lookUp(resort.base_lat, resort.base_lon);
        if (grid) grids[resort.id] = grid;
      } catch (err) {
        failures.push(`${resort.id}: ${err.message}`);
      }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // A partial run must not wipe out cells resolved by an earlier one.
  const previous = fs.existsSync(GRIDS_PATH)
    ? JSON.parse(fs.readFileSync(GRIDS_PATH, 'utf8')).grids
    : {};
  for (const failure of failures) {
    const id = failure.split(':')[0];
    if (previous[id]) grids[id] = previous[id];
  }

  const sorted = Object.fromEntries(Object.entries(grids).sort(([a], [b]) => a.localeCompare(b)));
  fs.writeFileSync(
    GRIDS_PATH,
    JSON.stringify(
      {
        $comment:
          'NWS grid cell per US resort, from api.weather.gov/points. Generated by scripts/build-nws-grids.js; do not edit by hand.',
        grids: sorted,
      },
      null,
      2
    ) + '\n'
  );

  for (const resort of resorts) {
    if (resort.country !== 'US') continue;
    resort.nws_grid = sorted[resort.id] || null;
  }
  fs.writeFileSync(RESORTS_PATH, JSON.stringify(resorts, null, 0));

  console.log(`✅ ${Object.keys(sorted).length}/${us.length} resolved`);
  if (failures.length) {
    console.warn(`⚠️  ${failures.length} failed (previous cells kept where known):`);
    for (const failure of failures) console.warn(`   ${failure}`);
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
